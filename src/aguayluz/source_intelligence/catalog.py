def _req(
    domain: str,
    source: str,
    role: CoverageRole,
    *,
    required: bool = False,
    adapter_required: bool = False,
) -> DomainSourceRequirement:
    return DomainSourceRequirement(
        domain_id=domain,
        source_family_id=source,
        role=role,
        required=required,
        adapter_required=adapter_required,
        state=CoverageState.REGISTERED,
    )


